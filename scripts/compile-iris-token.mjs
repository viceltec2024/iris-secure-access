import fs from "node:fs";
import path from "node:path";
import solc from "solc";

const root = process.cwd();
const source = fs.readFileSync(path.join(root, "contracts/IRISToken.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "contracts/IRISToken.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), {
  import(importPath) {
    const resolved = path.join(root, "node_modules", importPath);
    return fs.existsSync(resolved)
      ? { contents: fs.readFileSync(resolved, "utf8") }
      : { error: `Import not found: ${importPath}` };
  },
}));

const failures = (output.errors || []).filter(error => error.severity === "error");
if (failures.length) throw new Error(failures.map(error => error.formattedMessage).join("\n"));

const contract = output.contracts["contracts/IRISToken.sol"].IRISToken;
const artifact = `// Generated by scripts/compile-iris-token.mjs.\nexport const IRIS_TOKEN_ABI = ${JSON.stringify(contract.abi)} as const;\nexport const IRIS_TOKEN_BYTECODE = "0x${contract.evm.bytecode.object}" as const;\n`;
fs.writeFileSync(path.join(root, "app/dashboard/iris-token-artifact.ts"), artifact);
