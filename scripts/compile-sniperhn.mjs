import fs from "node:fs";
import path from "node:path";
import solc from "solc";

const root = process.cwd();
const sourcePath = path.join(root, "contracts/SNIPERHN.sol");
const remixSourcePath = path.join(root, "contracts/remix/SNIPERHN.sol");
const flattenedPath = path.join(root, "contracts/remix/SNIPERHN.flattened.sol");
const artifactPath = path.join(root, "app/sniperhn/sniperhn-artifact.ts");
const remixMetaPath = path.join(root, "app/sniperhn/sniperhn-remix.ts");

function resolveImport(fromFile, spec) {
  if (spec.startsWith("@openzeppelin/")) {
    return path.join(root, "node_modules", spec.replace(/@[\d.]+(?=\/)/, ""));
  }
  return path.resolve(path.dirname(fromFile), spec);
}

function flatten(entryFile) {
  const seen = new Set();
  const chunks = [];
  const importLine = /^\s*import\s+(?:\{[^}]*\}\s+from\s+)?["']([^"']+)["']\s*;\s*$/gm;

  function visit(file) {
    const abs = path.resolve(file);
    if (seen.has(abs)) return;
    seen.add(abs);
    const source = fs.readFileSync(abs, "utf8");
    const deps = [];
    const withoutImports = source.replace(importLine, (_match, spec) => {
      deps.push(spec);
      return "";
    });
    for (const spec of deps) visit(resolveImport(abs, spec));
    const cleaned = withoutImports
      .replace(/^\s*\/\/ SPDX-License-Identifier:.*$/gm, "")
      .replace(/^\s*pragma solidity.*$/gm, "")
      .trim();
    chunks.push(`// File: ${path.relative(root, abs)}\n${cleaned}`);
  }

  visit(entryFile);
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

${chunks.join("\n\n")}
`;
}

function compile(file, content) {
  const output = JSON.parse(solc.compile(JSON.stringify({
    language: "Solidity",
    sources: { [file]: { content } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
    },
  }), {
    import(importPath) {
      const resolved = importPath.startsWith("@openzeppelin/")
        ? path.join(root, "node_modules", importPath.replace(/@[\d.]+(?=\/)/, ""))
        : path.join(root, importPath);
      return fs.existsSync(resolved)
        ? { contents: fs.readFileSync(resolved, "utf8") }
        : { error: `Import not found: ${importPath}` };
    },
  }));
  const failures = (output.errors || []).filter(error => error.severity === "error");
  if (failures.length) throw new Error(failures.map(error => error.formattedMessage).join("\n"));
  const contracts = output.contracts[file];
  const name = Object.keys(contracts).find(key => key === "SNIPERHN") || Object.keys(contracts).at(-1);
  return contracts[name];
}

const source = fs.readFileSync(sourcePath, "utf8");
const remixSource = fs.readFileSync(remixSourcePath, "utf8");
const flattened = flatten(sourcePath);
fs.mkdirSync(path.dirname(flattenedPath), { recursive: true });
fs.writeFileSync(flattenedPath, flattened);

const local = compile("contracts/SNIPERHN.sol", source);
const remix = compile("contracts/remix/SNIPERHN.sol", remixSource);
const flat = compile("contracts/remix/SNIPERHN.flattened.sol", flattened);
if (!local.evm.bytecode.object || !remix.evm.bytecode.object || !flat.evm.bytecode.object) {
  throw new Error("SNIPERHN bytecode was empty");
}
if (JSON.stringify(local.abi) !== JSON.stringify(remix.abi) || JSON.stringify(local.abi) !== JSON.stringify(flat.abi)) {
  throw new Error("SNIPERHN ABI mismatch across Remix sources");
}

fs.mkdirSync(path.dirname(artifactPath), { recursive: true });
fs.writeFileSync(artifactPath, `// Generated by scripts/compile-sniperhn.mjs.
export const SNIPERHN_ABI = ${JSON.stringify(local.abi)} as const;
export const SNIPERHN_BYTECODE = "0x${local.evm.bytecode.object}" as const;
`);

const remixCode = Buffer.from(remixSource, "utf8").toString("base64");
const remixUrl = `https://app.remix.live/?#activate=solidity,udapp&autoCompile=true&optimize=true&language=Solidity&theme=Dark&version=soljson-v0.8.36+commit.8a079791.js&code=${remixCode}`;
fs.writeFileSync(remixMetaPath, `// Generated by scripts/compile-sniperhn.mjs.
export const SNIPERHN_NAME = "SNIPERHN";
export const SNIPERHN_SYMBOL = "SNIPERHN";
export const SNIPERHN_DECIMALS = 18;
export const SNIPERHN_TOTAL_SUPPLY = "1000000000";
export const SNIPERHN_COMPILER = "0.8.36+commit.8a079791";
export const SNIPERHN_REMIX_SOURCE = ${JSON.stringify(remixSource)};
export const SNIPERHN_REMIX_URL = ${JSON.stringify(remixUrl)};
`);

console.log(`Compiled SNIPERHN (${local.evm.bytecode.object.length / 2} bytes) and wrote Remix artifacts.`);
